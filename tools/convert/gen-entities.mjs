#!/usr/bin/env node
// The HTML named character references (plan P3-35: the converter kit's
// entity decoder) from the WHATWG list, https://html.spec.whatwg.org/entities.json
// → tools/convert/entities.gen.mjs. Needs the network; run when the list
// changes (it is append-only in practice).
//   node tools/convert/gen-entities.mjs
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const res = await fetch('https://html.spec.whatwg.org/entities.json');
if (!res.ok) throw new Error(`entities.json: HTTP ${res.status}`);
const all = await res.json();
// "&amp;" and "&amp" (the legacy ones without ';'): name → characters
const withSemi = {}, legacy = [];
for (const [k, v] of Object.entries(all)) {
  if (k.endsWith(';')) withSemi[k.slice(1, -1)] = v.characters;
  else legacy.push(k.slice(1));
}
const names = Object.keys(withSemi).sort();
const out = `// GENERATED by tools/convert/gen-entities.mjs from https://html.spec.whatwg.org/entities.json — do not edit.
// The HTML named character references: name (without & and ;) → characters;
// LEGACY: the names a document may write without the ';'.
export const ENTITIES = Object.freeze(${JSON.stringify(Object.fromEntries(names.map((n) => [n, withSemi[n]])))});
export const LEGACY = Object.freeze(new Set(${JSON.stringify(legacy.sort())}));
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), 'entities.gen.mjs'), out);
console.log(`entities.gen.mjs: ${names.length} names, ${legacy.length} legacy`);
