#!/usr/bin/env node
// The hand-written tsm grammars from the engine's syntax table (plan P1-09):
// both read their delimiters, classes and limits from
// grammar/tree-sitter-tsm/syntax-regex.js (← runtime/src/shared/syntax.gen.json
// ← engine/src/syntax/syntax.def).
//   editors/vscode-tsm/syntaxes/tsm.tmLanguage.json   TextMate first-paint grammar
//   third_party/grammars/tsm/{parser.c,tree_sitter/}  `tree-sitter generate` of
//                                                     grammar/tree-sitter-tsm/grammar.js
// The highlight query has one copy: grammar/tree-sitter-tsm/highlights.scm.
// Run by tools/gen-all.mjs; `--check` fails on stale outputs.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const require = createRequire(import.meta.url);
const grammarDir = join(root, 'grammar/tree-sitter-tsm');
const R = require(join(grammarDir, 'syntax-regex.js'));
let stale = 0;

function emit(rel, text) {
  const p = join(root, rel);
  const old = existsSync(p) ? readFileSync(p) : null;
  const buf = Buffer.isBuffer(text) ? text : Buffer.from(text);
  if (old && old.equals(buf)) return;
  if (CHECK) {
    console.error(`stale: ${rel} (run node tools/gen-grammars.mjs)`);
    stale++;
    return;
  }
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, buf);
  console.log(`wrote ${rel}`);
}

// ---- TextMate ---------------------------------------------------------------
const delim = (name) => ({ name });
const fenceLang = (id, langs, scope, include) => ({
  begin: `^(${R.fenceRun})\\s*(?i:(${langs}))\\b[^\\n]*$`,
  beginCaptures: { 1: delim('punctuation.definition.markdown.tsm'), 2: delim('fenced_code.block.language.tsm') },
  end: '^(\\1)\\s*$',
  endCaptures: { 1: delim('punctuation.definition.markdown.tsm') },
  contentName: `meta.embedded.block.${scope}`,
  patterns: [{ include }],
});
const EMBEDDED = [
  ['javascript', 'js|javascript|mjs', 'javascript', 'source.js'],
  ['typescript', 'ts|typescript', 'typescript', 'source.ts'],
  ['json', 'json', 'json', 'source.json'],
  ['python', 'py|python', 'python', 'source.python'],
  ['cpp', 'cpp|c\\+\\+|cc|c', 'cpp', 'source.cpp'],
  ['rust', 'rs|rust', 'rust', 'source.rust'],
  ['tsm', 'tsm', 'tsm', 'source.tsm'],
];
const tm = {
  $schema: 'https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json',
  name: 'Typesetter Markup',
  scopeName: 'source.tsm',
  comment: `GENERATED by tools/gen-grammars.mjs from the engine's syntax table (syntax version ${R.version}) — do not edit. ` +
    'Coarse first-paint grammar: precise coloring comes from the engine (semantic tokens, tsr_syntax_tokens).',
  patterns: [
    { include: '#block-comment' },
    ...EMBEDDED.map(([id]) => ({ include: `#fence-${id}` })),
    { include: '#fence' },
    { include: '#heading' },
    { include: '#region' },
    { include: '#code-statement' },
    { include: '#code-block' },
    { include: '#rule' },
    { include: '#inline' },
  ],
  repository: {
    'block-comment': { name: 'comment.block.tsm', begin: R.commentOpen, end: R.commentClose },
    fence: {
      name: 'markup.raw.block.tsm',
      begin: `^(${R.fenceRun})([^\\n]*)$`,
      beginCaptures: { 1: delim('punctuation.definition.markdown.tsm'), 2: delim('fenced_code.block.language.tsm') },
      end: '^(\\1)\\s*$',
      endCaptures: { 1: delim('punctuation.definition.markdown.tsm') },
    },
    heading: {
      name: 'markup.heading.tsm',
      match: `^(={1,${R.headingMax}}) .*$`,
      captures: { 1: delim('punctuation.definition.heading.tsm') },
    },
    region: {
      match: `^(${R.regionOpen}|${R.regionClose})(${R.regionArgs})?\\s*$`,
      captures: { 1: delim('keyword.control.region.tsm'), 2: delim('meta.function-call.arguments.tsm') },
    },
    'code-statement': { name: 'keyword.control.let.tsm', match: `^${R.statement}$` },
    // #{ … }: JavaScript, closed on its own line or by a line starting '}'
    'code-block': {
      patterns: [
        { name: 'meta.embedded.block.javascript', match: `^${R.stmtOpen}.*\\}\\s*$` },
        {
          begin: `^(${R.stmtOpen})(?!.*\\}\\s*$)`,
          beginCaptures: { 1: delim('punctuation.section.embedded.begin.tsm') },
          end: '^(\\})',
          endCaptures: { 1: delim('punctuation.section.embedded.end.tsm') },
          contentName: 'meta.embedded.block.javascript',
          patterns: [{ include: 'source.js' }],
        },
      ],
    },
    rule: { name: 'meta.separator.tsm', match: `^${R.ruleLine}$` },
    inline: {
      patterns: [
        { name: 'markup.inline.raw.tsm', match: R.code },
        { name: 'string.other.math.tsm', match: R.math },
        { name: 'markup.bold.tsm', match: R.strong },
        { name: 'markup.italic.tsm', match: R.em },
        {
          match: `(${R.linkText})(${R.linkUrl})`,
          captures: { 1: delim('string.other.link.title.tsm'), 2: delim('markup.underline.link.tsm') },
        },
        { name: 'constant.other.reference.tsm', match: R.reference },
        { name: 'entity.name.label.tsm', match: R.label },
        { name: 'keyword.control.flow.tsm', match: `${R.keywordHead}(?!\\w)` },
        { name: 'keyword.control.flow.tsm', match: '(?<=\\]|\\] )else\\b' },
        { name: 'entity.name.function.splice.tsm', match: R.splice },
      ],
    },
    ...Object.fromEntries(EMBEDDED.map(([id, langs, scope, include]) =>
      [`fence-${id}`, fenceLang(id, langs, scope, include)])),
  },
};
emit('editors/vscode-tsm/syntaxes/tsm.tmLanguage.json', JSON.stringify(tm, null, 2) + '\n');

// ---- tree-sitter ------------------------------------------------------------
const ts = join(root, 'node_modules/.bin/tree-sitter');
if (!existsSync(ts)) {
  console.error('gen-grammars: node_modules/.bin/tree-sitter missing (npm install)');
  process.exit(1);
}
const out = mkdtempSync(join(tmpdir(), 'tsm-grammar-'));
try {
  execFileSync(ts, ['generate', join(grammarDir, 'grammar.js'), '-o', out], {
    cwd: grammarDir, stdio: ['ignore', 'ignore', 'inherit'],
  });
  emit('third_party/grammars/tsm/parser.c', readFileSync(join(out, 'parser.c')));
  for (const h of readdirSync(join(out, 'tree_sitter')).sort())
    emit(`third_party/grammars/tsm/tree_sitter/${h}`, readFileSync(join(out, 'tree_sitter', h)));
} finally {
  rmSync(out, { recursive: true, force: true });
}

if (stale) process.exit(1);
